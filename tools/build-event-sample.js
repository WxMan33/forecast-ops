#!/usr/bin/env node
/* Builds docs/beta/event-sample.html: the Event Manager page exactly as event-beta.html, plus the synthetic Orlando
   design fixture (tests/fixtures/event-orlando-data.js). For design review on the beta preview only; the page says on
   screen that its weather is synthetic. It stores nothing in the browser: the event travels in the link.
   Run after changing event-beta.html: node tools/build-event-sample.js */
'use strict';
const fs = require('node:fs'), path = require('node:path'), root = path.resolve(__dirname, '..');
let html = fs.readFileSync(path.join(root, 'event-beta.html'), 'utf8');
/* resolve every asset and navigation link from the site root, as event-beta.html does */
html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="../../">');
const tag = html.match(/<script src="assets\/beta-event\.js\?v=[^"]+"><\/script>/);
if (!tag) throw new Error('beta-event.js script tag not found in event-beta.html');
html = html.replace(tag[0], `<script src="tests/fixtures/event-orlando-data.js"></script>\n${tag[0]}`)
  .replace(/<title>[^<]*<\/title>/, '<title>Event Manager design sample (synthetic weather) · Forecast Ops</title>')
  .replace('<!--load-guard-->', '<!-- generated by tools/build-event-sample.js from event-beta.html; do not edit by hand -->\n<!--load-guard-->');
fs.writeFileSync(path.join(root, 'docs/beta/event-sample.html'), html);
console.log('wrote docs/beta/event-sample.html');
