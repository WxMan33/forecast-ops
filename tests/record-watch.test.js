'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const R=require('../assets/record-watch.js');
const fixture=JSON.parse(fs.readFileSync('tests/fixtures/almanac/acis-records2-CVGthr-11-03.json')).json;
const rec=R.records(fixture.data,'2026-11-03');
assert.equal(rec.highMax.value,81);assert.deepEqual(rec.highMax.years,[1946]);assert.equal(rec.lowMin.value,12);assert(rec.highMin&&rec.lowMax);
assert(R.eligible({lat:39.0461,lon:-84.6622}));assert(!R.eligible({lat:39.1245,lon:-84.5038}));assert(!R.eligible({lat:0,lon:0}));
const row={hours:24,hi:79,lo:14};
assert.equal(R.assess(row,'hi',rec)[0].status,'Near record');assert.equal(R.assess(row,'lo',rec)[0].color,'cold');
assert.equal(R.assess({...row,hi:81},'hi',rec)[0].status,'Potential tie');
assert.equal(R.assess({...row,hi:82},'hi',rec)[0].status,'Potential record');
assert.equal(R.assess({...row,hi:78},'hi',rec).length,0);
assert.equal(R.assess({...row,hours:23},'hi',rec).length,0);assert.equal(R.assess({...row,hours:25},'hi',rec).length,0);assert.equal(R.assess({...row,hours:12},'hi',rec).length,0);
assert.equal(R.assess({...row,hi:null},'hi',rec).length,0);assert.equal(R.assess(row,'hi',{}).length,0);
assert.equal(Object.keys(R.records([['2025-11-03','M','M']],'2026-11-03')).length,0);
assert.equal(R.records([...fixture.data,['2026-11-03','100','-20'],['2025-11-04','110','-30']],'2026-11-03').highMax.value,81);
assert.equal(R.assess({...row,hi:rec.lowMax.value},'hi',rec).find(x=>x.key==='lowMax').color,'cold');
assert.equal(R.assess({...row,lo:rec.highMin.value},'lo',rec).find(x=>x.key==='highMin').color,'warm');
console.log('21 record-watch checks pass (official captured Cincinnati records, all four extremes, partial days, missing values and location gating)');
