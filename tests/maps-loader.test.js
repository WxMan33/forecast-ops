"use strict";
const assert = require("node:assert/strict"), fs = require("fs"), path = require("path"), zlib = require("zlib");
const L = require("../assets/maps-loader.js"), MC = require("../assets/maps-core.js");
const dir = path.join(__dirname, "fixtures/maps/2026110418"), man = JSON.parse(fs.readFileSync(path.join(dir, "manifest.json")));
const calls = [], failures = new Set();
const bytes = (file) => { const b = zlib.gunzipSync(fs.readFileSync(path.join(dir, file))); return b.buffer.slice(b.byteOffset, b.byteOffset + b.length); };
const loader = L.create({ json: async (url) => { calls.push(url); return structuredClone(man); }, buffer: async (url) => {
  calls.push(url); const file = url.split("/").pop(); if (failures.has(file)) throw new Error("test outage"); return bytes(file);
}, decode: MC.field });
const count = (name) => calls.filter((s) => s.endsWith(name)).length;
(async () => {
  const a = await loader.open("a", "/a");
  assert.deepEqual(calls, ["/a/manifest.json", "/a/latlon.bin.gz"], "opening a run never fetches weather fields");
  await loader.ensure(a, "t2m");
  assert.deepEqual(Object.keys(a.fields), ["t2m"]);
  assert.equal(a.loaded, man.grid.latlon.gzipBytes + man.fields.t2m.gzipBytes);
  const cell = man.grid.checkpoints.points[0].cell;
  assert.equal(a.fields.t2m.at(0, ...cell), MC.field(man.fields.t2m, bytes(man.fields.t2m.file), man.hours.length, man.grid.ny, man.grid.nx).at(0, ...cell));
  await Promise.all([loader.ensure(a, "refc"), loader.ensure(a, "refc")]);
  assert.equal(count("refc.bin.gz"), 1, "concurrent selections share a field download");
  await loader.ensure(a, "precip", "6");
  assert.equal(count("apcp_hour.bin.gz"), 1);
  assert.equal(count("apcp_run.bin.gz"), 0, "hourly totals do not load since-run-start data");
  await loader.ensure(a, "precip", "run");
  assert.equal(count("apcp_run.bin.gz"), 1);
  const totals = a.loaded;
  await loader.ensure(a, "t2m"); assert.equal(a.loaded, totals, "cached switches don't count bytes twice");
  assert.equal(await loader.open("a", "/a"), a, "returning to a retained run reuses its arrays");
  await assert.rejects(loader.ensure(a, "refd1km"), /not published/);
  assert.equal(count("refd1km.bin.gz"), 0);
  const b = await loader.open("b", "/b"); failures.add("refc.bin.gz");
  await assert.rejects(loader.ensure(b, "refc"), /test outage/);
  assert.equal(b.fields.refc, undefined); assert.equal(b.loaded, man.grid.latlon.gzipBytes);
  failures.clear(); await loader.ensure(b, "refc");
  assert.ok(b.fields.refc, "failed fields can be retried without replacing a good run");
  assert.equal(a.fields.refc.at(0, ...cell), b.fields.refc.at(0, ...cell));
  await loader.open("a", "/a"); await loader.open("c", "/c");
  assert.equal(await loader.open("a", "/a"), a, "least-recently-used run, not active run, was evicted");
  assert.notEqual(await loader.open("b", "/b"), b);
  const bad = L.create({ json: async () => man, buffer: async () => new ArrayBuffer(4), decode: MC.field });
  await assert.rejects(bad.open("bad", "/bad"), /coordinate size/);
  await assert.rejects(bad.open("bad", "/bad"), /coordinate size/, "failed run can be retried");
  console.log("Map loader: demand-only downloads, run-local values, shared requests, precipitation dependencies, cache limits and recovery pass");
})().catch((e) => { console.error(e); process.exitCode = 1; });
