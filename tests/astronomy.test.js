'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),P=require('../tools/refresh-astronomy.js'),K=require('../assets/astronomy-core.js');let n=0;
const eq=(a,b,m)=>{assert.deepEqual(a,b,m);n++;};const ok=(x,m)=>{assert.ok(x,m);n++;};const bad=(f,m)=>{assert.throws(f,undefined,m);n++;};
const at=Date.parse('2026-11-04T15:00Z'),html=fs.readFileSync('tests/fixtures/astro/nasa-iss-cincinnati-20261104.html','utf8'),f=P.parse(html,at);
eq(f.passes.length,14,'all actual NASA rows parsed');
eq(f.passes.find(p=>p.date==='2026-11-04').start,'2026-11-04T11:00:00.000Z','Cincinnati local time becomes UTC');
eq(f.passes.find(p=>p.date==='2026-11-05').durationLessThan,true,'less than one minute retained');
eq(f.passes.find(p=>p.date==='2026-11-08').start,'2026-11-09T00:29:00.000Z','evening pass bins by local calendar date, not UTC date');
eq(K.issDay(f,'2026-11-06',at).status,'ready','no listed pass is distinct from unavailable data');
eq(K.issDay(f,'2026-11-06',at).next.date,'2026-11-08','quiet date links to the next actual listed opportunity');
eq(K.issDay(f,'2026-11-04',at).next.date,'2026-11-05','expired morning pass does not hide the next upcoming pass');
eq(K.issDay(f,'2026-11-06',at).passes.length,0,'quiet listed date');
eq(K.issDay(f,'2026-11-25',at).status,'outside','outside horizon never means no passes');
eq(K.issDay(f,'2026-11-05',at+4*86400000).status,'stale','stale schedule suppressed');
eq(K.issDay(null,'2026-11-05',at).status,'unavailable','fetch failure not treated as clear');
eq(K.issDay({...f,retrievedAt:'2027-01-01T00:00Z'},'2026-11-05',at).status,'unavailable','future-dated retrieval rejected');
ok(K.issDay(f,'2026-11-04',at).upcoming.every(p=>p.date>'2026-11-04'&&p.date<'2026-11-11'),'next several days use selected day');
bad(()=>P.parse(html.replaceAll('Cincinnati','Dayton'),at),'wrong city rejected');
bad(()=>P.parse(html.replace('Max Height','Altitude'),at),'schema change fails closed');
bad(()=>P.parse(html.replace('17&deg;</td>','199&deg;</td>'),at),'invalid elevation rejected');
bad(()=>P.parse(html,Date.parse('2026-12-31T12:00Z')),'old table cannot silently become a new-year prediction');
const calendar=K.calendar(f.passes.find(p=>p.date==='2026-11-08'),at);
ok(calendar.includes('DTSTART:20261109T002900Z'),'calendar uses exact UTC instant across midnight');
ok(calendar.includes('TRIGGER:-PT15M'),'explicit calendar reminder');
ok(calendar.replace(/\r\n /g,'').includes('Rounded prediction'),'calendar does not present rounded duration as exact end');
ok(calendar.split('\r\n').every(line=>Buffer.byteLength(line)<=75),'RFC calendar lines folded by UTF-8 bytes');
ok(!calendar.includes('\n')||calendar.replace(/\r\n/g,'').indexOf('\n')<0,'CRLF calendar format');
const c=JSON.parse(fs.readFileSync('assets/sky-events.json'));
eq(K.skyDay(c,'2026-11-04').events[0].id,'sta2026','selected-night meteor entry');
eq(K.skyDay(c,'2026-11-08').events.length,0,'no invented special event');
eq(K.skyDay(c,'2027-03-01').reviewed,false,'unreviewed is not an empty complete calendar');
eq(K.skyDay(c,'2026-11-15').events[0].id,'planets2026','planet entry follows date selector');
const before=P.parse(html.replace('Tue Nov 03, 5:12 AM','Sat Oct 31, 6:00 AM'),at).passes[0];
eq(before.start,'2026-10-31T10:00:00.000Z','daylight-time row uses EDT before the change');
const after=P.parse(html.replace('Tue Nov 03, 5:12 AM','Sun Nov 01, 6:00 AM'),at).passes[0];
eq(after.start,'2026-11-01T11:00:00.000Z','standard-time row uses EST after the change');
bad(()=>P.parse(html.replace('Tue Nov 03, 5:12 AM','Sun Nov 01, 1:30 AM'),at),'ambiguous local time fails closed');
console.log(`${n} astronomy source, date, freshness and calendar checks pass`);
